// Generates src/runtime/arginfo.js: the signatures of the methods of PHP's internal classes
// that NIP implements, taken from the reference `php` binary's Reflection. NIP's own
// implementations (src/prelude/*.php, native classes) don't always declare the same parameter
// and return types; inheritance checks use these signatures instead.
//
//   node scripts/gen-arginfo.js        (needs `php` 8.3 on PATH)
import fs from 'node:fs';
import path from 'node:path';
import cp from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const names = new Set();
for (const f of fs.readdirSync(path.join(root, 'src/prelude'))) {
  const src = fs.readFileSync(path.join(root, 'src/prelude', f), 'utf8');
  for (const m of src.matchAll(/^(?:abstract |final |readonly )*(?:class|interface|trait|enum) (\w+)/gm)) if (!m[1].startsWith('__')) names.add(m[1]);
}
const nip = cp.execFileSync('node', [path.join(root, 'bin/nip.js'), '-r', 'echo implode("\\n", array_merge(get_declared_classes(), get_declared_interfaces()));'], { encoding: 'utf8' });
for (const n of nip.split('\n')) if (n && !n.startsWith('__')) names.add(n);

const php = `<?php
$out = [];
foreach (array_filter(explode("\\n", stream_get_contents(STDIN))) as $c) {
  if (!class_exists($c) && !interface_exists($c)) continue;
  $rc = new ReflectionClass($c);
  if (!$rc->isInternal()) continue;
  $ms = [];
  foreach ($rc->getMethods() as $m) {
    if ($m->getDeclaringClass()->getName() !== $rc->getName() || $m->isPrivate()) continue;
    $ps = [];
    foreach ($m->getParameters() as $p) {
      $def = null;
      if ($p->isOptional() && !$p->isVariadic() && preg_match('/ = (.*) \\]$/', (string) $p, $mm)) $def = $mm[1];
      $ps[] = [$p->hasType() ? (string) $p->getType() : '', $p->getName(), ($p->isPassedByReference() ? 1 : 0) | ($p->isVariadic() ? 2 : 0) | ($p->isOptional() ? 4 : 0), $def];
    }
    $ret = $m->hasReturnType() ? (string) $m->getReturnType() : ($m->hasTentativeReturnType() ? (string) $m->getTentativeReturnType() : '');
    $ms[strtolower($m->getName())] = [$m->getName(), $ret, $m->hasTentativeReturnType() ? 1 : 0, $m->returnsReference() ? 1 : 0, $ps];
  }
  $out[strtolower($c)] = [$rc->getName(), $ms, $rc->getExtensionName()];
}
ksort($out);
echo json_encode($out, JSON_UNESCAPED_SLASHES);
`;
const tmp = path.join(fs.mkdtempSync(path.join(process.env.TMPDIR || '/tmp', 'arginfo-')), 'gen.php');
fs.writeFileSync(tmp, php);
const data = JSON.parse(cp.execFileSync('php', [tmp], { input: [...names].join('\n'), encoding: 'utf8' }));
fs.rmSync(path.dirname(tmp), { recursive: true });

let js = `// Generated by scripts/gen-arginfo.js from PHP ${cp.execFileSync('php', ['-r', 'echo PHP_VERSION;'], { encoding: 'utf8' })}. Do not edit.
// class => [name, { method => [name, returnType, tentative, byRefReturn, [[type, name, flags, default]]] }, extension]
// parameter flags: 1 by reference, 2 variadic, 4 optional
export const CLASS_ARGINFO = {\n`;
for (const [k, v] of Object.entries(data)) js += `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
js += '};\n';
fs.writeFileSync(path.join(root, 'src/runtime/arginfo.js'), js);
console.log(`wrote ${Object.keys(data).length} classes to src/runtime/arginfo.js`);
